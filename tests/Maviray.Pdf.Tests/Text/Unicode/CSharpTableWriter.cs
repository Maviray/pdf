using System.Globalization;
using System.Text;

namespace Maviray.Pdf.Tests.Text.Unicode;

/// <summary>
/// Writes one generated C# file: the header the spec asks for (T-02), then one static class of constants and
/// <c>ReadOnlySpan&lt;T&gt;</c> properties over constant arrays. The output uses LF line endings and invariant number
/// formats, so it is the same on every machine.
/// </summary>
internal sealed class CSharpTableWriter
{
    private const int ValuesPerLine = 16;

    private readonly StringBuilder text = new();
    private readonly string fileName;
    private bool hasMember;

    public CSharpTableWriter(string className, string summary, IEnumerable<string> sourceFiles)
    {
        fileName = className + ".cs";
        Line("// <auto-generated/>");
        Line($"// Unicode Character Database {UcdFiles.Version}, https://www.unicode.org/Public/{UcdFiles.Version}/ucd/");
        Line($"// Source files: {string.Join(", ", sourceFiles)}.");
        Line("// Generated by tests/Maviray.Pdf.Tests/Text/Unicode/UnicodeTableGenerator.cs.");
        Line("// Do not edit. Regenerate with MAVIRAY_PDF_WRITE_UNICODE_TABLES=true, as CONTRIBUTING.md describes.");
        Line("//");
        foreach (var line in UcdFiles.ReadText("license.txt").TrimEnd('\n').Split('\n'))
        {
            Line(line.Length == 0 ? "//" : "// " + line);
        }

        Line();
        Line("namespace Maviray.Pdf.Text.Unicode;");
        Line();
        Line("/// <summary>");
        Line($"/// {Escape(summary)}");
        Line("/// </summary>");
        Line($"internal static class {className}");
        Line("{");
    }

    public void Constant(string name, int value, string summary)
    {
        Separate();
        Summary(summary);
        Line($"    public const int {name} = {value.ToString(CultureInfo.InvariantCulture)};");
    }

    /// <summary>Writes the values as decimal numbers.</summary>
    public void Array(string name, string elementType, IEnumerable<int> values, string summary) =>
        Array(name, elementType, values.Select(v => v.ToString(CultureInfo.InvariantCulture)), summary);

    /// <summary>Writes the values as <c>0x</c> hexadecimal numbers with at least the given number of digits.</summary>
    public void HexArray(string name, string elementType, IEnumerable<ulong> values, int digits, string summary) =>
        Array(name, elementType, values.Select(v => "0x" + v.ToString("X" + digits.ToString(CultureInfo.InvariantCulture), CultureInfo.InvariantCulture)), summary);

    public GeneratedFile ToFile()
    {
        Line("}");
        return new GeneratedFile(fileName, text.ToString());
    }

    private void Array(string name, string elementType, IEnumerable<string> values, string summary)
    {
        Separate();
        Summary(summary);
        Line($"    public static ReadOnlySpan<{elementType}> {name} => new {elementType}[]");
        Line("    {");
        var row = new List<string>(ValuesPerLine);
        foreach (var value in values)
        {
            row.Add(value);
            if (row.Count == ValuesPerLine)
            {
                Line("        " + string.Join(", ", row) + ",");
                row.Clear();
            }
        }

        if (row.Count > 0)
        {
            Line("        " + string.Join(", ", row) + ",");
        }

        Line("    };");
    }

    private void Separate()
    {
        if (hasMember)
        {
            Line();
        }

        hasMember = true;
    }

    private void Summary(string summary)
    {
        Line("    /// <summary>");
        Line($"    /// {Escape(summary)}");
        Line("    /// </summary>");
    }

    private static string Escape(string summary) => summary
        .Replace("&", "&amp;", StringComparison.Ordinal)
        .Replace("<", "&lt;", StringComparison.Ordinal)
        .Replace(">", "&gt;", StringComparison.Ordinal);

    private void Line(string line = "") => text.Append(line).Append('\n');
}
